"""The dataset card (datasets/README.md), rendered from the build metrics. No timestamps."""

from typing import Any


def _table(rows: dict[str, int], head: str) -> str:
    lines = [f"| {head} | Count |", "| --- | --- |"]
    lines += [f"| {k} | {v} |" for k, v in rows.items()]
    return "\n".join(lines)


def render_card(m: dict[str, Any]) -> str:
    splits = ("train", "validation", "test")
    size_rows = [
        f"| {task} | " + " | ".join(str(n[s]) for s in splits) + " |"
        for task, n in m["records"].items()
    ]
    a = m["alignment"]
    held = ", ".join(m["holdout_templates"]) or "none"
    return f"""# necrohub datasets

Generated by `necrohub build-dataset`; do not edit. Rebuilt from the seed with `make demo`.

> **Synthetic data only. Not for clinical, medico-legal or forensic use.** Every report, name and
> identifier was generated by the necrohub pipeline. No real person or case is described.

## Provenance

- Source: the processed layer (`documents.jsonl`) and the generator's gold records (`raw/gold`).
- Seed {m["seed"]}; {m["documents"]} documents; split by case with a seeded hash.
- NER spans are the generator's gold spans, projected from each raw txt onto the processed text
  (difflib, whitespace-insensitive). Rejected projections: {a["rejected"]} of
  {a["projected"] + a["rejected"]} spans (reject rate {a["reject_fraction"]}); the NER records of
  the {a["ner_records_dropped"]} section(s) that lost a span are dropped.
- Content sha256 of this directory: see `metrics/build_dataset.json` (`datasets_sha256`).

## Tasks and split sizes

| Task | train | validation | test |
| --- | --- | --- | --- |
{chr(10).join(size_rows)}

- `ner`: one record per report section, character spans of every entity label (PII and
  clinical) relative to the record text. BIO tags are built at training time.
- `sections`: section bodies without their header line, labelled with the section.
- `extraction`: redacted report text in, the non-PII case facts out (scenario, cause, mechanism,
  manner, post-mortem interval, injuries, organ findings). The input is redacted with the gold PII
  spans projected onto the processed text plus the regex de-identifier's detections, so it hides
  PII the regex alone misses. A case with a gold PII span that did not project is left out
  ({a["extraction_records_dropped"]} case(s)); the build fails if any gold PII value of a case
  remains in its input.
- `qa`: questions from fixed pt-BR templates, answers from the gold case facts.

Cases per split: {", ".join(f"{s} {m['cases'][s]}" for s in splits)}.

## Held-out templates

Cases written with the template(s) {held} appear only in `test`, so test measures transfer to a
report layout the models never saw in training.

## Label histograms

{_table(m["ner_labels"], "NER label")}

{_table(m["section_labels"], "Section label")}

## Known limits

- Template-generated text is repetitive; scores on it are optimistic.
- ETNIA, SEXO and standalone UF are not redacted in `extraction` inputs (decision 11): they are
  medical descriptors, not direct identifiers.
- Leaving out cases whose PII did not project means PDF-sourced reports are under-represented
  in `extraction`.
- Names come from Faker and may match real people by chance.
- QA answers come from the case facts; with the LLM realizer a report may phrase or omit a fact
  differently.
"""
